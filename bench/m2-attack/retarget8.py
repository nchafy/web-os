#!/usr/bin/env python3
"""Re-target m2_swing_before_flush onto today's commitOnce, mechanically.

The mutation's INTENT is fixed: the blob's flush moves to AFTER the journal record and its flush,
so a record on disk points at data that is not durable. Its anchor is not — the commit body has
changed four times, and this round added the apply's undo and the flush's errno, which is what
broke all four existing candidates.

So the candidate is GENERATED from the current src/kernel/store.mjs rather than typed: the span
from the flush comment to `this.stats.swings += 1;` is lifted verbatim, the flush block is cut out
of it and re-inserted immediately before the swing counter, and the pair is appended to mutate.py
as one more candidate. A typed anchor would be wrong again next round; a generated one is wrong
only if the span itself stops existing, and then it reports ANCHOR-GONE rather than a mutation the
suite caught.
"""
import pathlib
import sys

SRC = pathlib.Path("/Users/chafyni/claude/web-os/.claude/worktrees/webos-impl/src/kernel/store.mjs")
MUTATE = pathlib.Path("/Users/chafyni/.claude/jobs/e856c39e/tmp/mutate.py")

HEAD = "    // 1. the blob, 2. its flush. Durable BEFORE anything points at it.\n"
TAIL = "    this.stats.swings += 1;\n"


def main() -> int:
    text = SRC.read_text(encoding="utf-8")
    a = text.find(HEAD)
    b = text.find(TAIL, a)
    if a < 0 or b < 0:
        print("the commit span is not where it was", file=sys.stderr)
        return 9
    span = text[a:b + len(TAIL)]
    # The flush block: the `if (!this.cfg.noCowOrder) { … }` under the comment, by LINES — the
    # inner `if (flushed < 0) {` closes with a deeper brace, and a substring search for the outer
    # one finds that first.
    lines = span[len(HEAD):].splitlines(keepends=True)
    opened = next((i for i, ln in enumerate(lines)
                   if ln == "    if (!this.cfg.noCowOrder) {\n"), None)
    closed = next((i for i, ln in enumerate(lines) if i > (opened if opened is not None else 0)
                   and ln == "    }\n"), None)
    if opened is None or closed is None:
        print("the blob flush block is not where it was", file=sys.stderr)
        return 9
    block = "".join(lines[opened:closed + 1])
    rest = "".join(lines[:opened]) + "".join(lines[closed + 1:])
    if "IO_FSYNC" not in block or "blobFlushes" not in block:
        print("the block lifted is not the blob flush", file=sys.stderr)
        return 9
    moved = (
        "    // MUTATION: the blob's flush is moved to AFTER the journal record and its flush, so\n"
        "    // the record on disk points at data that is not durable.\n"
        + rest[:rest.rfind(TAIL)] + block + TAIL
    )
    if span.count(HEAD) != 1 or text.count(span) != 1:
        print("the span is not unique", file=sys.stderr)
        return 9

    mutate = MUTATE.read_text(encoding="utf-8")
    marker = '    # 3. The I/O worker ignores the refcount'
    if marker not in mutate:
        marker = '    "m3_refcount_ignored": ['
    if marker not in mutate:
        print("mutate.py's m3 entry was not found, so there is nowhere to insert", file=sys.stderr)
        return 9
    if "GENERATED by retarget8.py" in mutate:
        # Replace the previous generation rather than stacking candidates: two generated anchors
        # would both match nothing next round and the count in the failure message would lie.
        start = mutate.find("    ), (\n        # GENERATED by retarget8.py")
        end = mutate.find("    )],\n", start)
        mutate = mutate[:start] + "    )],\n" + mutate[end + len("    )],\n"):]
    insert = (
        "    ), (\n"
        "        # GENERATED by retarget8.py against the commit body of this round. Do not edit by\n"
        "        # hand: re-run the generator instead.\n"
        "        \"src/kernel/store.mjs\",\n"
        f"        {span!r},\n"
        f"        {moved!r},\n"
        "    )],\n"
    )
    at = mutate.find('    "m2_swing_before_flush": [(')
    end = mutate.find("    )],\n", at)
    mutate = mutate[:end] + insert + mutate[end + len("    )],\n"):]
    MUTATE.write_text(mutate, encoding="utf-8")
    print("mutate.py: m2_swing_before_flush re-targeted onto the current commit body")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
